import os
from io import BytesIO
from flask import Blueprint, request, jsonify, current_app, abort
from werkzeug.utils import secure_filename
import pydicom

from models import db, Patient
from dicom_utils import (
    load_dicom,
    dicom_to_jpeg,
    ensure_patient_folder,
    upsert_patient,
    upsert_study,
    upsert_series,
    upsert_instance
)
from Blueprints.auth.routes import login_required

stow_bp = Blueprint("stow_bp", __name__)

ALLOWED_CONTENT_TYPES = (
    "application/dicom",
    "application/octet-stream",
    "multipart/related",
)


class PatientIdentityConflictError(ValueError):
    """Raised when uploaded files conflict with an existing patient identity."""


def _norm(value):
    if value is None:
        return None
    text = str(value).strip()
    return text.lower() if text else None


def _assert_patient_identity_consistent(patient_id, name=None, sex=None, dob=None):
    existing = Patient.query.filter_by(patient_id=patient_id).first()
    if not existing:
        return

    conflicts = []
    existing_name, incoming_name = _norm(existing.patient_name), _norm(name)
    if existing_name and incoming_name and existing_name != incoming_name:
        conflicts.append(f"name existing='{existing.patient_name}' incoming='{name}'")

    existing_sex, incoming_sex = _norm(existing.patient_sex), _norm(sex)
    if existing_sex and incoming_sex and existing_sex != incoming_sex:
        conflicts.append(f"sex existing='{existing.patient_sex}' incoming='{sex}'")

    existing_dob, incoming_dob = _norm(existing.patient_dob), _norm(dob)
    if existing_dob and incoming_dob and existing_dob != incoming_dob:
        conflicts.append(f"dob existing='{existing.patient_dob}' incoming='{dob}'")

    if conflicts:
        raise PatientIdentityConflictError(
            f"PatientID '{patient_id}' already exists with different demographics: " + "; ".join(conflicts)
        )

def _save_dataset_to_disk(ds, base_patient_dir, filename=None):
    """
    Persist a pydicom Dataset to disk and return the absolute path.
    If filename is None, derive from SOPInstanceUID.
    """
    if not filename:
        sop = getattr(ds, "SOPInstanceUID", None) or getattr(ds, "SOPInstanceUID", "")
        filename = f"{secure_filename(sop)}.dcm" if sop else "unknown.dcm"
    os.makedirs(base_patient_dir, exist_ok=True)
    out_path = os.path.join(base_patient_dir, filename)
    # Save dataset to file
    ds.save_as(out_path, write_like_original=True)
    return out_path

def _extract_patient_id(ds, form_patient_id=None):
    pid = None
    # DICOM uses PatientID (0010,0020) – pydicom maps as 'PatientID'
    try:
        pid = getattr(ds, "PatientID", None)
    except Exception:
        pid = None
    if not pid:
        pid = form_patient_id
    return pid

@stow_bp.route("/studies", methods=["POST"])
@login_required
def stow_studies():
    """
    STOW-RS: store DICOM instances.
    Accepts multipart/related uploads (or single-dataset bodies).
    Returns JSON listing stored instances and errors.
    """
    # Optional: Basic content-type check
    content_type = request.headers.get("Content-Type", "")
    if not any(ct in content_type for ct in ALLOWED_CONTENT_TYPES):
        # still allow—some clients omit content-type; do not fail strictly
        current_app.logger.debug("STOW: unexpected Content-Type: %s", content_type)

    stored = []
    errors = []

    # Helper to process an individual file-like object (bytes or FileStorage)
    def _process_file_bytes(file_bytes, filename_hint=None):
        try:
            bio = BytesIO(file_bytes)
            ds = pydicom.dcmread(bio, force=True)  # force allows non-standard headers sometimes
        except Exception as e:
            raise RuntimeError(f"Failed to parse DICOM: {str(e)}")

        # Patient id can come from form or dataset
        patient_id = _extract_patient_id(ds, request.form.get("PatientID"))
        if not patient_id:
            # You may opt to reject here; for now, create an autogenerated patient id if missing
            raise RuntimeError("No PatientID found in DICOM nor request form")
        patient_id = str(patient_id).strip()

        form_patient_id = (request.form.get("PatientID") or "").strip()
        if form_patient_id and form_patient_id != patient_id:
            raise PatientIdentityConflictError(
                f"Request PatientID '{form_patient_id}' does not match DICOM PatientID '{patient_id}'"
            )

        # Ensure patient folder exists
        base_patient_dir = ensure_patient_folder(patient_id)  # returns absolute or relative path depending on helper
        # Save raw dicom to disk: use SOPInstanceUID for filename if present
        sop_uid = getattr(ds, "SOPInstanceUID", None)
        filename = f"{secure_filename(sop_uid)}.dcm" if sop_uid else (filename_hint or "unknown.dcm")
        saved_path = _save_dataset_to_disk(ds, base_patient_dir, filename)

        # Convert DICOM fields to safe strings
        patient_name = str(getattr(ds, "PatientName", "")) if getattr(ds, "PatientName", None) else None
        patient_sex = str(getattr(ds, "PatientSex", "")) if getattr(ds, "PatientSex", None) else None
        patient_dob = str(getattr(ds, "PatientBirthDate", "")) if getattr(ds, "PatientBirthDate", None) else None

        _assert_patient_identity_consistent(
            patient_id=patient_id,
            name=patient_name,
            sex=patient_sex,
            dob=patient_dob,
        )

        # Upsert patient
        patient = upsert_patient(patient_id=patient_id, name=patient_name, sex=patient_sex, dob=patient_dob)

        # Extract Study / Series / Instance UIDs (required for PACS)
        study_uid = getattr(ds, "StudyInstanceUID", None)
        series_uid = getattr(ds, "SeriesInstanceUID", None)
        sop_uid = getattr(ds, "SOPInstanceUID", None)

        if not all([study_uid, series_uid, sop_uid]):
            # Option: continue and store, but better to report error
            raise RuntimeError("Missing one of StudyInstanceUID / SeriesInstanceUID / SOPInstanceUID")

        # Upsert study, series, instance using your helpers (note signature alignment)
        study = upsert_study(patient, study_uid, study_date=str(getattr(ds, "StudyDate", None)) if getattr(ds, "StudyDate", None) else None, description=str(getattr(ds, "StudyDescription", None)) if getattr(ds, "StudyDescription", None) else None)
        series = upsert_series(study, series_uid, modality=str(getattr(ds, "Modality", None)) if getattr(ds, "Modality", None) else None, body_part=str(getattr(ds, "BodyPartExamined", None)) if getattr(ds, "BodyPartExamined", None) else None)

        # Generate preview JPEG (store under <patient_dir>/previews/<SOP>.jpg)
        preview_dir = os.path.join(base_patient_dir, "previews")
        os.makedirs(preview_dir, exist_ok=True)
        try:
            preview_path = dicom_to_jpeg(ds, preview_dir, sop_uid)
        except Exception as e:
            # If preview generation fails, continue but record preview as None
            current_app.logger.exception("Preview generation failed for %s", sop_uid)
            preview_path = None

        # Upsert instance (your signature: upsert_instance(series, sop_uid, file_path, preview_path, instance_number=None))
        instance = upsert_instance(series, sop_uid, saved_path, preview_path, instance_number=getattr(ds, "InstanceNumber", None))

        # Return a record to report back
        return {
            "sopInstanceUID": sop_uid,
            "studyInstanceUID": study_uid,
            "seriesInstanceUID": series_uid,
            "file_path": saved_path,
            "preview_path": preview_path,
        }

    # Primary: iterate request.files (multipart)
    if request.files:
        for key in request.files:
            fs = request.files.get(key)
            try:
                file_bytes = fs.read()
                result = _process_file_bytes(file_bytes, filename_hint=secure_filename(fs.filename or "upload.dcm"))
                stored.append(result)
            except PatientIdentityConflictError as e:
                current_app.logger.warning("STOW patient identity conflict for file %s: %s", getattr(fs, "filename", None), str(e))
                errors.append(
                    {
                        "filename": getattr(fs, "filename", None),
                        "error": str(e),
                        "type": "patient_identity_conflict",
                    }
                )
                try:
                    db.session.rollback()
                except Exception:
                    pass
            except Exception as e:
                current_app.logger.exception("STOW processing failed for uploaded file: %s", getattr(fs, "filename", None))
                errors.append({"filename": getattr(fs, "filename", None), "error": str(e)})
                # rollback until next file processing to keep DB consistent per-file
                try:
                    db.session.rollback()
                except Exception:
                    pass

    else:
        # Fallback: single-body DICOM (raw bytes)
        try:
            raw = request.get_data()
            if not raw:
                return jsonify({"error": "No files in request"}), 400
            try:
                result = _process_file_bytes(raw, filename_hint="upload.dcm")
                stored.append(result)
            except PatientIdentityConflictError as e:
                current_app.logger.warning("STOW patient identity conflict for raw body: %s", str(e))
                errors.append({"filename": None, "error": str(e), "type": "patient_identity_conflict"})
                try:
                    db.session.rollback()
                except Exception:
                    pass
            except Exception as e:
                current_app.logger.exception("STOW processing failed for raw body")
                errors.append({"filename": None, "error": str(e)})
                try:
                    db.session.rollback()
                except Exception:
                    pass
        except Exception as e:
            return jsonify({"error": "Failed reading request body", "detail": str(e)}), 400

    # At this stage some instances may have been added; commit remaining session state
    try:
        db.session.commit()
    except Exception:
        current_app.logger.exception("Final commit failed in STOW")
        try:
            db.session.rollback()
        except Exception:
            pass
        return jsonify({"stored": stored, "errors": errors, "message": "Partial failure during commit"}), 500

    # Return a helpful JSON response summarizing inserted instances
    response_body = {
        "stored": stored,
        "errors": errors,
        "message": f"{len(stored)} instance(s) stored"
    }
    # Use application/json — clients expect JSON; DICOMweb strict will expect application/dicom+json, you can change header if needed.
    return jsonify(response_body), 200
